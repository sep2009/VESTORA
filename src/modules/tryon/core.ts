export type ProbeOk = { ok: true; mime: "image/jpeg" | "image/png" | "image/webp"; width: number; height: number };
export type ProbeFail = { ok: false; code: "empty" | "type" | "corrupt"; message: string };
const u16be = (b: Uint8Array, o: number) => (b[o]! << 8) | b[o + 1]!;
const u32be = (b: Uint8Array, o: number) => ((b[o]! << 24) | (b[o + 1]! << 16) | (b[o + 2]! << 8) | b[o + 3]!) >>> 0;
const u32le = (b: Uint8Array, o: number) => (b[o]! | (b[o + 1]! << 8) | (b[o + 2]! << 16) | (b[o + 3]! << 24)) >>> 0;
const ascii = (b: Uint8Array, o: number, n: number) => String.fromCharCode(...b.subarray(o, o + n));
const bad = (message: string): ProbeFail => ({ ok: false, code: "corrupt", message });

/** Identify a photo by its bytes (never by name or claimed type) and read its size. JPEG, PNG and WebP only. */
export function probeImage(b: Uint8Array): ProbeOk | ProbeFail {
  if (b.length === 0) return { ok: false, code: "empty", message: "The file is empty." };
  if (b.length >= 8 && b[0] === 0x89 && ascii(b, 1, 3) === "PNG") {
    if (b.length < 33 || ascii(b, 12, 4) !== "IHDR") return bad("This PNG looks damaged.");
    return { ok: true, mime: "image/png", width: u32be(b, 16), height: u32be(b, 20) };
  }
  if (b.length >= 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) {
    let o = 2;
    while (o + 9 < b.length) {
      if (b[o] !== 0xff) { o++; continue; }
      const m = b[o + 1]!;
      if (m === 0xff) { o++; continue; }
      if (m === 0xd8 || m === 0x01 || (m >= 0xd0 && m <= 0xd7)) { o += 2; continue; }
      const len = u16be(b, o + 2);
      if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc) return { ok: true, mime: "image/jpeg", height: u16be(b, o + 5), width: u16be(b, o + 7) };
      if (m === 0xda) break;
      o += 2 + len;
    }
    return bad("This JPEG looks damaged.");
  }
  if (b.length >= 30 && ascii(b, 0, 4) === "RIFF" && ascii(b, 8, 4) === "WEBP") {
    const t = ascii(b, 12, 4);
    if (t === "VP8 ") return { ok: true, mime: "image/webp", width: (b[26]! | (b[27]! << 8)) & 0x3fff, height: (b[28]! | (b[29]! << 8)) & 0x3fff };
    if (t === "VP8L" && b[20] === 0x2f) return { ok: true, mime: "image/webp", width: 1 + (b[21]! | ((b[22]! & 0x3f) << 8)), height: 1 + ((b[22]! >> 6) | (b[23]! << 2) | ((b[24]! & 0x0f) << 10)) };
    if (t === "VP8X") return { ok: true, mime: "image/webp", width: 1 + (b[24]! | (b[25]! << 8) | (b[26]! << 16)), height: 1 + (b[27]! | (b[28]! << 8) | (b[29]! << 16)) };
    return bad("This WebP looks damaged.");
  }
  return { ok: false, code: "type", message: "Use a JPEG, PNG or WebP photo." };
}
export type PhotoCheck = ProbeOk | { ok: false; code: string; message: string };
export function checkPhoto(b: Uint8Array): PhotoCheck {
  if (b.length > PHOTO_LIMITS.maxBytes) return { ok: false, code: "too_large", message: `The photo is larger than ${PHOTO_LIMITS.maxBytes / 1024 / 1024} MB.` };
  const p = probeImage(b); if (!p.ok) return p;
  if (p.width < PHOTO_LIMITS.minSide || p.height < PHOTO_LIMITS.minSide) return { ok: false, code: "too_small", message: `The photo is too small. Each side must be at least ${PHOTO_LIMITS.minSide} pixels.` };
  if (p.width > PHOTO_LIMITS.maxSide || p.height > PHOTO_LIMITS.maxSide || p.width * p.height > PHOTO_LIMITS.maxPixels) return { ok: false, code: "too_big_dimensions", message: "The photo has too many pixels. Resize it and try again." };
  return p;
}

/** Remove metadata that can identify a person or place (EXIF/GPS, XMP, IPTC, text comments). Image data is untouched. */
export function stripMetadata(b: Uint8Array, mime: string): Uint8Array {
  const out: number[][] = [];
  if (mime === "image/jpeg") {
    out.push([0xff, 0xd8]);
    let o = 2;
    while (o + 4 <= b.length) {
      if (b[o] !== 0xff) break;
      const m = b[o + 1]!;
      if (m === 0xda) { return concat([...out.map((x) => Uint8Array.from(x)), b.subarray(o)]); }
      if (m === 0xd9) { out.push([0xff, 0xd9]); return concat(out.map((x) => Uint8Array.from(x))); }
      const len = u16be(b, o + 2), seg = b.subarray(o, o + 2 + len);
      const drop = m === 0xe1 || m === 0xed || m === 0xfe || (m >= 0xe3 && m <= 0xef && m !== 0xee);
      if (!drop) out.push(Array.from(seg));
      o += 2 + len;
    }
    return concat([...out.map((x) => Uint8Array.from(x)), b.subarray(Math.min(o, b.length))]);
  }
  if (mime === "image/png") {
    const parts: Uint8Array[] = [b.subarray(0, 8)];
    let o = 8;
    while (o + 12 <= b.length) {
      const len = u32be(b, o), type = ascii(b, o + 4, 4), end = o + 12 + len;
      if (!["eXIf", "tEXt", "zTXt", "iTXt", "tIME"].includes(type)) parts.push(b.subarray(o, end));
      o = end; if (type === "IEND") break;
    }
    return concat(parts);
  }
  if (mime === "image/webp") {
    const parts: Uint8Array[] = [];
    let o = 12;
    while (o + 8 <= b.length) {
      const type = ascii(b, o, 4), len = u32le(b, o + 4), end = o + 8 + len + (len & 1);
      if (type !== "EXIF" && type !== "XMP ") {
        const chunk = Uint8Array.from(b.subarray(o, Math.min(end, b.length)));
        if (type === "VP8X") chunk[8] = chunk[8]! & ~0x0c; // clear the EXIF and XMP flags
        parts.push(chunk);
      }
      o = end;
    }
    const body = concat(parts), head = new Uint8Array(12);
    head.set(b.subarray(0, 12));
    const total = body.length + 4; head[4] = total & 255; head[5] = (total >> 8) & 255; head[6] = (total >> 16) & 255; head[7] = (total >> 24) & 255;
    return concat([head, body]);
  }
  return b;
}
function concat(parts: Uint8Array[]): Uint8Array {
  const n = parts.reduce((s, p) => s + p.length, 0), r = new Uint8Array(n); let o = 0;
  for (const p of parts) { r.set(p, o); o += p.length; }
  return r;
}

