/** Garment kinds (from the catalog category) that photo try-on can handle. Shoes, bags and accessories are not supported. */
export function garmentCategoryFor(kind: string): GarmentCategory | null {
  switch (kind) {
    case "tee": case "shirt": case "hoodie": return "upper_body";
    case "trousers": return "lower_body";
    case "dress": return "dress";
    case "jacket": case "coat": case "suit": return "outerwear";
    default: return null;
  }
}

